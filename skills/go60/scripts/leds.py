"""Go60 per-key LED colour presets (config/led-presets.json): validation, loading, saving and the C
header the firmware build uses. Shared by go60-leds and the app page (app.py).
"""

import json
import os
import re
from pathlib import Path

import keymap as km

PRESETS_FILE = Path(os.environ.get("GO60_LED_PRESETS") or km.REPO_DIR / "config" / "led-presets.json")
STOCK_EFFECTS = ["Solid", "Breathe", "Spectrum", "Swirl"]
MAX_PRESETS = 16
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")
NAMES = [km.position_name(i) for i in range(60)]


def validate(data):
    """Return the normalized presets list, or raise ValueError."""
    if not isinstance(data, dict) or not isinstance(data.get("presets"), list):
        raise ValueError('expected {"presets": [...]}')
    presets = data["presets"]
    if len(presets) > MAX_PRESETS:
        raise ValueError(f"at most {MAX_PRESETS} presets")
    out, seen = [], set()
    for n, p in enumerate(presets, 1):
        name = str(p.get("name", "")).strip() if isinstance(p, dict) else ""
        if not name:
            raise ValueError(f"preset {n} has no name")
        if name.lower() in seen:
            raise ValueError(f"two presets are called {name!r}")
        seen.add(name.lower())
        keys = p.get("keys", {})
        if not isinstance(keys, dict):
            raise ValueError(f"{name}: keys must be an object")
        for k, c in keys.items():
            if k not in NAMES:
                raise ValueError(f"{name}: unknown key position {k!r} (e.g. 'LH C3R2', 'RH T1')")
            if not isinstance(c, str) or not HEX.match(c):
                raise ValueError(f"{name}: {k} colour {c!r} is not like #ff8800")
        # Keys left out are off. Store every key, in keyboard order, so diffs stay readable.
        out.append({"name": name, "keys": {k: keys.get(k, "#000000").lower() for k in NAMES}})
    return out


def load():
    if not PRESETS_FILE.exists():
        return []
    with open(PRESETS_FILE, encoding="utf-8") as f:
        return validate(json.load(f))


def save(presets):
    text = json.dumps({"presets": presets}, indent=2, ensure_ascii=False) + "\n"
    tmp = PRESETS_FILE.with_suffix(".json.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(PRESETS_FILE)


def display_path():
    try:
        return str(PRESETS_FILE.relative_to(km.REPO_DIR))
    except ValueError:
        return str(PRESETS_FILE)


def rgb(hexcolor):
    return tuple(int(hexcolor[i:i + 2], 16) for i in (1, 3, 5))


def header(presets):
    lines = ["// Generated by go60-leds from config/led-presets.json. Don't edit.", "#pragma once", "",
             "#include <zephyr/drivers/led_strip.h>", "",
             f"#define GO60_LED_PRESET_COUNT {len(presets)}",
             f"#define GO60_LED_PRESET_PIXELS {km.LEDS_PER_HALF}", ""]
    if not presets:
        return "\n".join(lines) + "\n"
    for side, cond in (("L", "#if IS_ENABLED(CONFIG_BOARD_GO60_LH)"), ("R", "#else")):
        lines.append(cond)
        lines.append(f"static const struct led_rgb go60_led_presets[{len(presets)}][{km.LEDS_PER_HALF}] = {{")
        for p in presets:
            leds = [(0, 0, 0)] * km.LEDS_PER_HALF
            for i in range(60):
                s, led = km.led_index(i)
                if s == side:
                    leds[led] = rgb(p["keys"][NAMES[i]])
            cells = ", ".join(f"{{.r = {r}, .g = {g}, .b = {b}}}" for r, g, b in leds)
            name = p["name"].replace("*/", "* /")
            lines.append(f"    /* {name} */ {{{cells}}},")
        lines.append("};")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def effect_list(presets):
    return STOCK_EFFECTS + [p["name"] for p in presets]
